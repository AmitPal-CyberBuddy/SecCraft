// Optional real-browser keyboard/theme smoke test; uses an offline API fixture.
import assert from 'node:assert/strict'
import fs from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
const modules=process.env.UI_AUDIT_MODULES
const { chromium }=await import(modules ? pathToFileURL(resolve(modules,'playwright/index.mjs')).href : 'playwright')
const baseUrl=process.env.UI_AUDIT_URL || 'http://localhost:3000'
const output=resolve(process.env.UI_AUDIT_OUTPUT || '.cache/ui-audit')
fs.mkdirSync(output,{recursive:true})
const browser=await chromium.launch({executablePath:process.env.UI_AUDIT_EXECUTABLE || undefined,args:['--no-sandbox'],headless:true})
const page=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'})
await page.route('**/api/**',route=>route.fulfill({status:503,contentType:'application/json',body:'{"detail":"QA offline fixture"}'}))
await page.goto(baseUrl+'/app',{waitUntil:'networkidle'})
await page.getByRole('link',{name:/Skip to/}).focus()
assert.match(await page.evaluate(()=>document.activeElement.textContent),/Skip/)
await page.keyboard.press('Enter')
assert.equal(await page.evaluate(()=>document.activeElement.tagName),'MAIN')
await page.getByRole('button',{name:'Open navigation menu',exact:true}).click()
assert.equal(await page.getByRole('button',{name:'Close navigation menu',exact:true}).getAttribute('aria-expanded'),'true')
await page.keyboard.press('Escape')
assert.equal(await page.evaluate(()=>document.activeElement.id),'mobile-navigation-toggle')
await page.getByRole('button',{name:'Search SecCraft',exact:true}).click()
assert.equal(await page.evaluate(()=>document.activeElement.tagName),'INPUT')
await page.keyboard.press('Escape')
await page.goto(baseUrl+'/settings',{waitUntil:'networkidle'})
const themes=page.getByRole('group',{name:'Theme preference'})
await themes.getByRole('button',{name:'Light',exact:true}).click()
assert.equal(await page.locator('html').getAttribute('data-theme'),'light')
await themes.getByRole('button',{name:'Use device setting',exact:true}).click()
await page.emulateMedia({colorScheme:'dark'})
await page.waitForFunction(()=>document.documentElement.dataset.theme==='dark')
await page.emulateMedia({colorScheme:'light'})
await page.waitForFunction(()=>document.documentElement.dataset.theme==='light')
await page.getByRole('button',{name:'Reset All Progress',exact:true}).click()
assert.equal(await page.getByRole('button',{name:'Confirm reset',exact:true}).count(),1)
await page.getByRole('button',{name:'Cancel',exact:true}).click()
assert.equal(await page.getByRole('button',{name:'Confirm reset',exact:true}).count(),0)
// Short landscape viewport: controls must remain reachable with local scrolling.
await page.setViewportSize({width:844,height:390})
await page.goto(baseUrl+'/reports',{waitUntil:'networkidle'})
await page.getByRole('button',{name:'Preview',exact:true}).click()
assert.equal(await page.getByRole('button',{name:'Preview',exact:true}).getAttribute('aria-pressed'),'true')
await page.getByRole('button',{name:'Edit',exact:true}).click()
assert.equal(await page.getByRole('button',{name:'Edit',exact:true}).getAttribute('aria-pressed'),'true')
await page.screenshot({path:output+'/reports-landscape.png',fullPage:true})
// Equivalent CSS reflow at 200% on a 1280px desktop. Not browser chrome zoom or device proof.
await page.setViewportSize({width:640,height:450})
await page.goto(baseUrl+'/settings',{waitUntil:'networkidle'})
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
await page.getByRole('link',{name:'Appearance',exact:true}).click()
await page.waitForTimeout(100)
assert.ok(await page.locator('#settings-appearance').evaluate(el=>el.getBoundingClientRect().top>=0))
console.log('PASS: skip link; mobile navigation Escape/focus return; search focus/Escape; dark/light/system live changes; reset cancellation; landscape report views; 640px CSS reflow and settings anchor.')
await browser.close()
