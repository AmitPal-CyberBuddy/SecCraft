// CSS and JavaScript share one authored definition. Check mode is used in tests.
import { readFileSync, writeFileSync } from 'node:fs'
const source = new URL('../frontend/src/design/motion-tokens.json', import.meta.url)
const target = new URL('../frontend/src/styles/motion-tokens.css', import.meta.url)
const tokens = JSON.parse(readFileSync(source, 'utf8'))
const durations = values => Object.entries(values).map(([key,value]) => `--motion-${key}:${value}ms;`).join(' ')
const quiet = durations(Object.fromEntries(Object.keys(tokens.duration).map(key => [key,0])))
const css = `/* Generated by scripts/generate-motion-tokens.mjs; edit design/motion-tokens.json. */
:root {
  ${durations(tokens.duration)}
  --motion-ease:cubic-bezier(${tokens.ease.join(',')});
  ${Object.entries(tokens.distance).map(([key,value]) => `--motion-distance-${key}:${value}px;`).join(' ')}
}
@media(max-width:680px),(max-height:500px) { :root { ${durations(tokens.compactDuration)} } }
@media(prefers-reduced-motion:reduce) { :root { ${quiet} } }
.reduce-motion,[data-motion="reduced"],[data-motion-paused="true"] { ${quiet} }
`
if (process.argv.includes('--check')) {
  if (readFileSync(target,'utf8') !== css) throw new Error('Motion tokens are stale. Run node scripts/generate-motion-tokens.mjs')
} else writeFileSync(target,css)
